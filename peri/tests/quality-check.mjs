import assert from 'node:assert/strict';
import { readFileSync, existsSync } from 'node:fs';
const root = new URL('../', import.meta.url);
const read = p => readFileSync(new URL(p, root), 'utf8');
const required = ['index.html','css/style.css','js/app.js','js/core.js','js/quiz.js','js/data.js','manifest.webmanifest','sw.js','icons/icon.svg','icons/favicon.svg',...['cafe','letters','clouds','frog','piano','treasure','shapes','colors'].map(x=>'js/games/'+x+'.js')];
for (const p of required) assert.ok(existsSync(new URL(p,root)), 'missing '+p);
const manifest = JSON.parse(read('manifest.webmanifest'));
assert.equal(manifest.lang, 'fa');
assert.equal(manifest.dir, 'rtl');
const data = read('js/data.js');
const letterBlock = data.split('export const LETTERS=')[1].split('export const FRUITS=')[0];
const fruitBlock = data.split('export const FRUITS=')[1].split('export const COLORS=')[0];
const colorBlock = data.split('export const COLORS=')[1].split('export const SHAPES=')[0];
assert.equal((letterBlock.match(/\['[^']+','[^']+','[^']+'\]/g)||[]).length, 30, 'expected 30 letters');
assert.equal((fruitBlock.match(/\['[^']+','[^']+'\]/g)||[]).length, 17, 'expected 17 fruits');
assert.equal((colorBlock.match(/\['[^']+','#?[0-9a-fA-F]{6}'\]/g)||[]).length, 17, 'expected 17 colors');
const app = read('js/app.js');
for (const g of ['cafe','letters','clouds','frog','piano','treasure','shapes','colors']) assert.ok(app.includes("['"+g+"'"), 'game not registered: '+g);
for (const p of required) assert.ok(!read(p).includes('\\n'), 'raw newline escape found in '+p);
console.log('Peri quality checks passed.');
